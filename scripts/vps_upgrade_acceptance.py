#!/usr/bin/env python3
"""Explicitly authorized, public-HTTPS Scenario A acceptance on fresh qa3 only.

Run on the VPS as root. Never initializes, resets or rotates an environment.
The execute stage prepares/approves one fresh case, checks replay, then restarts
only qa3. The model stage reads an existing qa3 case and calls the real SSE
assistant without approval. Every invocation requires a new output directory.
Invites, cookies, authorization material and answers are never published.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
import re
import subprocess
import time
import uuid
from datetime import UTC, datetime
from decimal import Decimal
from pathlib import Path
from urllib.parse import urlsplit

import httpx

from forgeflow.api.evidence import public_evidence
from forgeflow.judge_gateway import configuration as gateway_configuration
from forgeflow.product.reconciliation import _journal
from forgeflow.recovery.service import verify_sources
from forgeflow.recovery.storage import digest, read_json
from forgeflow.vps_runtime import configuration, trusted_json

ROOT = Path(__file__).resolve().parents[1]
INDEX = Path("/etc/forgeflow/reviewers.json")
GATEWAY = Path("/etc/forgeflow/gateway.json")
TABLES = ("purchase_order", "purchase_order_line", "mrp_production", "mrp_workorder",
          "sale_order", "sale_order_line", "stock_move", "stock_picking")
RESOURCE_KEYS = ("api_user", "dsh_user", "container", "api_port", "odoo_port", "service_unit")
PATH_KEYS = ("sandbox_root", "case_root", "data_root", "dsh_root", "socket")
# build_planner_bundle creates these package markers; they are deliberately not
# copies of the repository's package entry points. Verify exact generated bytes.
GENERATED_PACKAGE_MARKERS = frozenset({
    "forgeflow/__init__.py", "upstream/procurement/__init__.py", "upstream/schemas/__init__.py",
})


class AcceptanceFailure(RuntimeError):
    """A fixed diagnostic label safe to publish without subprocess/HTTP text."""


def need(condition, label):
    if not condition:
        raise AcceptanceFailure(label)


def command(*args, timeout=60):
    result = subprocess.run(args, capture_output=True, timeout=timeout)
    need(result.returncode == 0, "operator_command_failed")
    return result.stdout


def sha256(raw):
    return hashlib.sha256(raw).hexdigest()


def publish(value):
    value = public_evidence(value)
    if isinstance(value, dict):
        return {key: publish(item) for key, item in value.items()
                if key not in {"approver_label", "scope_id", "display_name", "answer"}}
    if isinstance(value, list):
        return [publish(item) for item in value]
    return value


def save(output, name, value):
    with (output / (name + ".json")).open("x", encoding="utf-8") as handle:
        json.dump(publish(value), handle, indent=2, ensure_ascii=False)
        handle.write("\n")


def validate_target(name, base, index, config, others, gateway):
    """Reject aliases to historical instances before any authentication or write."""
    need(name == "qa3", "only_new_qa3_is_allowed")
    item = index["instances"][name]
    need(item["id"] == name and config["instance_name"] == name
         and config["service_unit"] == item["service_unit"] == "forgeflow-runtime@qa3.service"
         and config["api_port"] == item["port"] and config["scenario"] == "A",
         "qa_identity_binding_mismatch")
    need(Path(config["repo_root"]).resolve() == ROOT, "wrong_deployed_repository")
    need(config.get("allow_initialize") is False, "initialization_must_be_disabled")
    for other in others:
        need(not any(config[key] == other[key] for key in RESOURCE_KEYS), "shared_qa_resource")
        need(not {config["api_user"], config["dsh_user"]}
             & {other["api_user"], other["dsh_user"]}, "shared_qa_identity")
        need(not {config["api_port"], config["odoo_port"]}
             & {other["api_port"], other["odoo_port"]}, "shared_qa_port")
        for key in PATH_KEYS:
            target = Path(config[key]).resolve()
            for other_key in PATH_KEYS:
                protected = Path(other[other_key]).resolve()
                need(not (target == protected or target in protected.parents
                          or protected in target.parents), "shared_qa_path")
    parsed = urlsplit(base)
    need(parsed.scheme == "https" and parsed.netloc in index["trusted_hosts"]
         and parsed.hostname and not parsed.username and not parsed.password
         and parsed.path in {"", "/"} and not parsed.query and not parsed.fragment,
         "trusted_public_https_required")
    need(gateway["public_tenant"] == "judge1", "public_default_changed")
    tenant = next((row for row in gateway["tenants"] if row["id"] == name), None)
    need(tenant and tenant["port"] == item["port"]
         and sha256(item["invite_code"].encode()) in tenant["invite_sha256"],
         "qa_gateway_binding_mismatch")
    need(len({item["invite_code"], index["legacy"]["invite_code"],
              *(row["invite_code"] for key, row in index["instances"].items() if key != name)})
         == len(index["instances"]) + 1, "shared_invite")


def load_target(name, base):
    need(name == "qa3", "only_new_qa3_is_allowed")
    index = trusted_json(INDEX)
    item = index["instances"][name]
    config = configuration(trusted_json(Path(item["config"])))
    others = [configuration(trusted_json(Path("/etc/forgeflow/runtime.json")))]
    others += [configuration(trusted_json(Path(row["config"])))
               for key, row in index["instances"].items() if key != name]
    gateway = gateway_configuration(trusted_json(GATEWAY))
    validate_target(name, base, index, config, others, gateway)
    instance = trusted_json(Path(config["sandbox_root"]) / "vps-instance.json")
    need(instance.get("phase") == "ready"
         and re.fullmatch(r"[0-9a-f]{32}", instance.get("generation", "")),
         "qa_generation_not_ready")
    need(command("systemctl", "is-active", config["service_unit"]).strip() == b"active",
         "qa_service_not_active")
    return item, config, instance


def active_bundle(config):
    return Path(config.get("active_bundle", str(Path(config["sandbox_root"]) / "planner")))


def sources(config):
    commit = command("git", "-C", str(ROOT), "rev-parse", "HEAD").decode().strip()
    need(re.fullmatch(r"[0-9a-f]{40}", commit), "invalid_source_commit")
    paths = sorted((ROOT / "src/forgeflow").rglob("*.py"))
    paths += [Path(__file__), *(ROOT / "scripts" / name for name in (
        "verify_next_phase.py", "vps_provision.py", "vps_reviewers.py"))]
    paths += [ROOT / "upstream.lock.json", ROOT / "uv.lock"]
    paths += sorted((ROOT / "src/forgeflow/api/static/app").rglob("*"))
    files = {str(path.relative_to(ROOT)): sha256(path.read_bytes())
             for path in paths if path.is_file()}
    bundle = active_bundle(config)
    provenance = verify_sources(bundle)
    need(GENERATED_PACKAGE_MARKERS <= provenance["files_sha256"].keys(),
         "qa_bundle_generated_marker_missing")
    matched, generated = {}, {}
    for name, expected in provenance["files_sha256"].items():
        if name in GENERATED_PACKAGE_MARKERS:
            need(expected == sha256(b"") and (bundle / name).read_bytes() == b"",
                 "qa_bundle_generated_marker_changed")
            generated[name] = expected
        elif name.startswith("forgeflow/"):
            source = ROOT / "src" / name
            need(source.is_file() and sha256(source.read_bytes()) == expected,
                 "qa_bundle_not_current_source")
            matched[name] = expected
    need(bool(matched), "qa_bundle_source_missing")
    return {"commit": commit, "files_sha256": files,
            "bundle_provenance_sha256": digest(provenance),
            "bundle_files_sha256": provenance["files_sha256"],
            "bundle_matches_current_source": matched,
            "bundle_generated_empty_package_markers": generated}


def tables(config):
    sql = " UNION ALL ".join(
        f"SELECT '{table}', count(*)::text, md5(coalesce(string_agg(to_jsonb(t)::text, '|' ORDER BY id), '')) FROM {table} t"
        for table in TABLES)
    raw = command("docker", "exec", "--user", "postgres", config["container"],
                  "psql", "-d", "bench", "-XAt", "-F", "|", "-c", sql)
    result = {}
    for line in raw.decode().splitlines():
        table, count, checksum = line.split("|")
        need(table in TABLES and re.fullmatch(r"[0-9a-f]{32}", checksum), "invalid_table_digest")
        result[table] = {"count": int(count), "rows_md5": checksum}
    need(set(result) == set(TABLES), "business_snapshot_incomplete")
    return result


def request(client, method, path, body=None, expected=200):
    response = client.request(method, path, json=body)
    need(response.status_code == expected, "unexpected_http_status")
    return response.json()


def authenticate(client, item, instance):
    response = client.post("/api/auth/session", json={"invite_code": item["invite_code"]})
    need(response.status_code == 201
         and all(response.cookies.get(key) for key in ("ff_session", "__Host-ff_route")),
         "gateway_authentication_failed")
    need(all("Secure" in value and "HttpOnly" in value
             for value in response.headers.get_list("set-cookie")), "unsafe_session_cookie")
    environment = request(client, "GET", "/api/environment")
    need(environment.get("generation") == instance["generation"], "wrong_gateway_generation")
    capabilities = request(client, "GET", "/api/capabilities")
    need(capabilities.get("environment", {}).get("execution") == "live_sandbox",
         "live_executor_missing")
    return environment


def require_fresh(client, config, environment):
    need(environment.get("available") is True and environment.get("owned_by_me") is False,
         "qa_generation_already_claimed")
    need(request(client, "GET", "/api/product/cases") == [], "qa_cases_not_empty")
    case_root = Path(config["case_root"])
    need(not any(re.fullmatch(r"[0-9a-f]{32}\.json", path.name)
                 for path in case_root.rglob("*.json")), "qa_has_persisted_cases")
    for folder in ("store", "approvals"):
        path = Path(config["sandbox_root"]) / folder
        need(not any(path.iterdir()), "qa_has_existing_plan_state")


def select_default(client, case):
    comparison = case.get("comparison") or {}
    candidates = comparison.get("plans") or []
    selected = next((p for p in candidates if p.get("objective") == "preserve_quantities"),
                    case.get("plan"))
    need(selected and selected.get("objective") == "preserve_quantities", "default_candidate_missing")
    plan_id = selected["plan_id"]
    need(re.fullmatch(r"[0-9a-f]{64}", plan_id), "invalid_plan_id")
    if case["state"] == "awaiting_selection" or (case.get("plan") or {}).get("plan_id") != plan_id:
        case = request(client, "POST", "/api/product/cases/" + case["case_id"] + "/select",
                       {"plan_id": plan_id, "comparison_id": comparison["comparison_id"],
                        "selection_revision": comparison["selection_revision"]})
    need(case["state"] == "awaiting_approval" and case.get("approval") is None
         and case.get("execution") is None, "plan_not_waiting_for_first_approval")
    return case


def independent_margin(config, case):
    spec = importlib.util.spec_from_file_location("upgrade_margin_check", ROOT / "scripts/verify_next_phase.py")
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    metrics = helper.independent_margin(Path(config["sandbox_root"]) / "store" / case["plan"]["plan_id"],
                                        case["plan"])
    need(Decimal(metrics["planned_cost"]) == Decimal("4794.94")
         and Decimal(metrics["new_spend_revenue"]) == Decimal("20623.23")
         and metrics["new_spend_units"] == 43 and metrics["stock_units"] == 7
         and metrics["repair_objective"] == 6, "a_default_baseline_changed")
    return metrics


def verify_execution(case, plan_id):
    execution = case.get("execution") or {}
    verifier = execution.get("verifier") or {}
    readback = execution.get("readback") or {}
    need(case.get("state") == "succeeded" and case.get("result", {}).get("verified") is True
         and case.get("approval", {}).get("plan_id") == plan_id
         and (case.get("plan") or {}).get("plan_id") == plan_id
         and verifier.get("strict_success") is True and verifier.get("evaluation_valid") is True
         and verifier.get("evaluation_scope") == "product_original_verifier"
         and verifier.get("passed_rule_count") == verifier.get("applicable_rule_count") == 51
         and verifier.get("failed_rule_count") == 0 and verifier.get("score") == 100
         and readback.get("execution_validated") is True and readback.get("verified_steps") == 7
         and len(case["plan"].get("actions", [])) == 2, "a_execution_not_verified")
    return execution


def verify_receipt(config, case, reward):
    """Compare HTTP evidence with the original immutable local receipt and inputs."""
    case_id, plan = case["case_id"], case["plan"]
    plan_id = plan["plan_id"]
    need(re.fullmatch(r"[0-9a-f]{32}", case_id)
         and re.fullmatch(r"[0-9a-f]{64}", plan_id), "invalid_receipt_identity")
    directory = Path(config["sandbox_root"]) / "store" / plan_id
    receipt = read_json(directory / "product-verification.json")
    need(isinstance(receipt, dict) and set(receipt) == {"payload", "sha256"}
         and isinstance(receipt["payload"], dict)
         and digest(receipt["payload"]) == receipt["sha256"], "local_receipt_digest_mismatch")
    payload = receipt["payload"]
    execution = case["execution"]
    readback, verifier = execution["readback"], execution["verifier"]
    need(receipt["sha256"] == readback.get("receipt_sha256")
         and payload.get("verified_steps") == readback.get("verified_steps")
         and payload.get("verified_at") == readback.get("verified_at")
         and payload.get("verifier") == verifier, "http_local_receipt_mismatch")
    manifest = read_json(directory / "manifest.json")
    provenance = verify_sources(active_bundle(config))
    need(digest(manifest) == plan_id and manifest.get("sources") == provenance,
         "receipt_plan_source_mismatch")
    snapshot_sha = digest(read_json(directory / "snapshot.json"))
    need(manifest["artifacts"]["snapshot"] == snapshot_sha == plan.get("snapshot_sha256")
         and manifest.get("policy_sha256") == plan.get("policy_sha256")
         and manifest.get("product", {}).get("run_id") == "local-" + case_id,
         "receipt_plan_input_mismatch")
    _, journal_sha = _journal(directory / "journal.jsonl")
    expected = {"run_id": "local-" + case_id, "case_id": case_id, "plan_id": plan_id,
                "policy_sha256": manifest["policy_sha256"], "snapshot_sha256": snapshot_sha,
                "journal_sha256": journal_sha, "readback_sha256": readback.get("readback_sha256"),
                "sources_sha256": digest(provenance)}
    need(all(isinstance(expected[key], str) and re.fullmatch(r"[0-9a-f]{64}", expected[key])
             for key in expected if key.endswith("sha256")), "invalid_receipt_binding_digest")
    bindings = payload.get("bindings")
    need(isinstance(bindings, dict) and all(bindings.get(key) == value for key, value in expected.items()),
         "local_receipt_binding_mismatch")
    original = payload.get("original_reward_json")
    need(isinstance(original, str) and original.encode() == reward
         and sha256(reward) == verifier.get("reward_sha256"), "local_receipt_reward_mismatch")
    return {"receipt_sha256": receipt["sha256"], "reward_sha256": sha256(reward),
            **{key: value for key, value in expected.items() if key.endswith("sha256")},
            "verified_binding_fields": list(expected), "http_receipt_matches_local": True}


def execute(client, config, instance, output, report):
    before = tables(config)
    save(output, "before-prepare-tables", before)
    case = request(client, "POST", "/api/product/cases", {"scenario": "A"}, expected=201)
    save(output, "prepared", case)
    need(re.fullmatch(r"[0-9a-f]{32}", case["case_id"]), "invalid_case_id")
    case = select_default(client, case)
    save(output, "selected", case)
    report.update(case_id=case["case_id"], plan_id=case["plan"]["plan_id"])
    report["margin"] = independent_margin(config, case)
    after_prepare = tables(config)
    save(output, "after-prepare-tables", after_prepare)
    need(before == after_prepare, "preparation_changed_business_tables")
    print(json.dumps({"stage": "prepared", "passed": True}), flush=True)
    url = "/api/product/cases/" + case["case_id"]
    payload = {"plan_id": report["plan_id"], "comment": "Authorized isolated public upgrade acceptance"}
    case = request(client, "POST", url + "/approve", payload)
    save(output, "executed", case)
    execution = verify_execution(case, report["plan_id"])
    reward = command("docker", "exec", config["container"], "cat", "/logs/verifier/reward.json")
    need(sha256(reward) == execution["verifier"]["reward_sha256"], "original_reward_hash_mismatch")
    json.loads(reward)
    receipt_binding = verify_receipt(config, case, reward)
    save(output, "receipt-binding", receipt_binding)
    with (output / "original-reward.raw.json").open("xb") as handle:
        handle.write(reward)
    after = tables(config)
    save(output, "after-approval-tables", after)
    need(after != before, "execution_did_not_change_business_tables")
    print(json.dumps({"stage": "approved_and_verified", "passed": True}), flush=True)
    repeated = request(client, "POST", url + "/approve", payload)
    need(repeated.get("execution") == execution and repeated.get("approval") == case.get("approval"),
         "replayed_approval_changed_receipt")
    need(verify_receipt(config, repeated, reward) == receipt_binding,
         "replayed_approval_changed_local_receipt")
    replay = tables(config)
    save(output, "after-replay-tables", replay)
    need(replay == after, "replayed_approval_changed_business_tables")
    print(json.dumps({"stage": "duplicate_approval", "passed": True}), flush=True)
    command("systemctl", "restart", config["service_unit"], timeout=1050)
    deadline = time.monotonic() + 120
    resumed = None
    while time.monotonic() < deadline:
        try:
            response = client.get(url)
            if response.status_code == 200:
                resumed = response.json()
                break
        except httpx.HTTPError:
            pass
        time.sleep(1)
    need(resumed is not None and resumed.get("execution") == execution
         and resumed.get("approval") == case.get("approval")
         and (resumed.get("plan") or {}).get("plan_id") == report["plan_id"],
         "restart_changed_receipt")
    need(verify_receipt(config, resumed, reward) == receipt_binding, "restart_changed_local_receipt")
    environment = request(client, "GET", "/api/environment")
    need(environment.get("generation") == instance["generation"]
         and environment.get("owned_by_me") is True, "restart_changed_generation_or_owner")
    restarted = tables(config)
    save(output, "after-restart-tables", restarted)
    save(output, "resumed", resumed)
    need(restarted == after, "restart_changed_business_tables")
    print(json.dumps({"stage": "service_restart", "passed": True}), flush=True)
    report.update(preparation_business_tables_unchanged=True, duplicate_approval_idempotent=True,
                  restart_preserves_receipt_and_business_tables=True,
                  business_actions=2, confirmed_execution_steps=7,
                  execution=execution)


def model(client, config, case_id, output, report):
    need(re.fullmatch(r"[0-9a-f]{32}", case_id or ""), "valid_existing_case_required")
    path = "/api/product/cases/" + case_id
    before = request(client, "GET", path)
    before_tables = tables(config)
    save(output, "before-model-tables", before_tables)
    body = {"question": "Explain what this case's execution evidence establishes and its limits.",
            "conversation_id": "upgrade-acceptance-" + uuid.uuid4().hex[:16],
            "turn_id": uuid.uuid4().hex, "resume": False}
    count, final = 0, None
    with client.stream("POST", path + "/ask/stream", json=body) as response:
        need(response.status_code == 200
             and response.headers.get("content-type", "").startswith("text/event-stream"),
             "model_sse_unavailable")
        for line in response.iter_lines():
            if not line.startswith("data:"):
                continue
            event = json.loads(line[5:].strip())
            count += 1
            need(event.get("type") != "error", "model_stream_failed")
            if event.get("type") == "final":
                final = event
                break
    need(final and final.get("mode") == "harness"
         and isinstance(final.get("answer"), str) and final["answer"].strip(),
         "real_model_final_missing")
    after = request(client, "GET", path)
    after_tables = tables(config)
    save(output, "after-model-tables", after_tables)
    need(before.get("execution") == after.get("execution")
         and before.get("approval") == after.get("approval")
         and before.get("plan") == after.get("plan") and before_tables == after_tables,
         "model_changed_business_state")
    report.update(case_id=case_id, event_count=count, final_mode="harness",
                  answer_nonempty=True, answer_sha256=sha256(final["answer"].encode()),
                  business_state_unchanged=True, business_approval_requested=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", required=True, choices=("qa3",))
    parser.add_argument("--base-url", required=True)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--stage", choices=("execute", "model"), default="execute")
    parser.add_argument("--execute", action="store_true", help="Authorize the selected operator stage")
    parser.add_argument("--case-id", help="Existing qa3 case for model stage only")
    args = parser.parse_args()
    report, output = None, None
    try:
        need(os.geteuid() == 0, "root_required")
        need(args.execute, "explicit_execute_authorization_required")
        need(args.stage == "model" or args.case_id is None, "execute_requires_fresh_case")
        os.umask(0o077)
        item, config, instance = load_target(args.name, args.base_url)
        need(not args.output.exists() and not args.output.is_symlink(), "new_output_directory_required")
        args.output.mkdir(parents=True, exist_ok=False, mode=0o700)
        output = args.output
        source = sources(config)
        save(output, "source", source)
        report = {"schema_version": 1, "name": args.name, "stage": args.stage,
                  "category": "public_https_dedicated_synthetic_product_acceptance",
                  "source_commit": source["commit"], "base_url": args.base_url,
                  "generation": instance["generation"], "odoo_image": config["odoo_image"],
                  "data_profile": "planning-metadata-v1",
                  "started_at": datetime.now(UTC).isoformat(), "status": "running",
                  "tls_verification": True, "official_or_historical_environments_used": False,
                  "approval_origin": "explicitly_authorized_http_driver" if args.stage == "execute" else None,
                  "browser_approval": False, "autonomous_benchmark": False,
                  "business_table_scope": list(TABLES), "all_database_writes_measured": False}
        with httpx.Client(base_url=args.base_url.rstrip("/"), headers={"Origin": args.base_url.rstrip("/")},
                          timeout=960, trust_env=False, follow_redirects=False) as client:
            environment = authenticate(client, item, instance)
            if args.stage == "execute":
                require_fresh(client, config, environment)
                execute(client, config, instance, output, report)
            else:
                model(client, config, args.case_id, output, report)
        need(sources(config) == source, "source_changed_during_acceptance")
        report.update(status="passed", source_unchanged=True)
    except Exception as error:
        label = str(error) if type(error) is AcceptanceFailure else type(error).__name__
        if report is not None:
            report.update(status="failed", error_code=label)
        print(json.dumps({"passed": False, "error_code": label}), flush=True)
        return 1
    finally:
        if report is not None:
            report["finished_at"] = datetime.now(UTC).isoformat()
            save(output, "report", report)
    manifest = {"files": {path.name: sha256(path.read_bytes()) for path in sorted(output.iterdir())},
                "scope": "Operator capture; hashes identify bytes, not independent attestation.",
                "redaction": "No credentials, cookies, authorization tokens, actor identities or model answers."}
    save(output, "manifest", manifest)
    print(json.dumps({"passed": True, "stage": args.stage, "name": args.name}), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
