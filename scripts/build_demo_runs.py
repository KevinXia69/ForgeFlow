#!/usr/bin/env python3
"""Build the curated, read-only run tree served by the ForgeFlow review API.

The builder copies only the files the product API actually opens. Everything
else in a recorded run stays behind: agent traces, prompts, provider request
logs, entrypoint/executor logs, task fixtures and implementation archives.

The output is deterministic: the destination is recreated from scratch, the
relative directory layout is preserved, and file bytes are copied unchanged.
Only Python's standard library is used.
"""

from __future__ import annotations

import argparse
import os
import shutil
import stat
import sys
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

RUN_IDS = (
    "permission-split-pi-20261021-09",
    "permission-split-pi-b-20261021-01",
    "p5-B-nop-meta-r1",
    "p5-heldout-2281-pi-r1",
)

# The API reads these run-level files directly.
FIXED_ALLOWLIST = (
    "manifest.json",
    "summary.json",
    "attestation/verifier.json",
    "attestation/verifier.sig",
)
# Paths relative to one harbor/job/<trial> directory.
TRIAL_ALLOWLIST = (
    "result.json",
    "verifier/reward.json",
    "verifier/reward.txt",
)
# Every regular file below harbor/job/*/agent/recovery is a plan artifact.
RECOVERY_ALLOWLIST = "harbor/job/*/agent/recovery/**"

README_NAME = "README.md"
MAX_FILE_BYTES = 2 * 1024 * 1024
MAX_TOTAL_BYTES = 20 * 1024 * 1024

README_TEMPLATE = """# ForgeFlow demo runs

This directory is a curated, read-only subset of recorded ForgeFlow runs (no
agent traces). It is generated by `scripts/build_demo_runs.py` and is not a
copy of the full run tree: prompts, provider logs, task fixtures and
implementation archives are deliberately excluded too.

Only the files the review API reads are present: the run manifest and summary,
the signed verifier attestation, the Harbor trial result and verifier reward,
and the recovery plan artifacts.

Do not edit this tree by hand. Regenerate it from the repository root with:

```bash
uv run python scripts/build_demo_runs.py
```

## Runs

{runs}
"""


class NoSelectedRuns(Exception):
    """None of the known run ids is present below the source directory."""


@dataclass(frozen=True)
class RunStats:
    """Per-run copy result printed by the CLI and asserted by tests."""

    run_id: str
    files: int
    bytes: int


def _regular(path: Path) -> bool:
    """True only for a regular file (symlinks are rejected by lstat)."""
    try:
        return stat.S_ISREG(path.lstat().st_mode)
    except OSError:
        return False


def _safe_regular(run_dir: Path, relative: Path) -> bool:
    """True when every path component is a real directory and the leaf is a file."""
    cursor = run_dir
    for part in relative.parts:
        cursor = cursor / part
        if cursor.is_symlink():
            return False
    return _regular(cursor)


def _trial_directories(run_dir: Path) -> Iterable[Path]:
    job = run_dir / "harbor" / "job"
    if job.is_symlink() or not job.is_dir():
        return
    for trial in sorted(job.iterdir(), key=lambda path: path.name):
        if trial.is_symlink() or not trial.is_dir():
            continue
        yield trial


def _trial_paths(run_dir: Path) -> Iterable[Path]:
    for trial in _trial_directories(run_dir):
        for relative in TRIAL_ALLOWLIST:
            candidate = Path("harbor/job") / trial.name / relative
            if _safe_regular(run_dir, candidate):
                yield candidate


def _recovery_paths(run_dir: Path) -> Iterable[Path]:
    """Walk only agent/recovery, never following a symlinked directory."""
    for trial in _trial_directories(run_dir):
        recovery = trial / "agent" / "recovery"
        if recovery.is_symlink() or not recovery.is_dir():
            continue
        for directory, dirnames, filenames in os.walk(recovery, followlinks=False):
            current = Path(directory)
            dirnames[:] = sorted(
                name for name in dirnames if not (current / name).is_symlink()
            )
            for name in sorted(filenames):
                path = current / name
                if path.is_symlink() or not _regular(path):
                    continue
                yield path.relative_to(run_dir)


def _candidates(run_dir: Path) -> list[Path]:
    found: set[Path] = set()
    for relative in FIXED_ALLOWLIST:
        candidate = Path(relative)
        if _safe_regular(run_dir, candidate):
            found.add(candidate)
    found.update(_trial_paths(run_dir))
    found.update(_recovery_paths(run_dir))
    return sorted(found, key=lambda path: path.as_posix())


def _guard_destination(source: Path, destination: Path) -> None:
    """Refuse paths whose cleanup could delete the source tree or the workspace."""
    if destination == source or source.is_relative_to(destination):
        raise ValueError("--out must not contain the --source tree")
    if destination.is_relative_to(source):
        raise ValueError("--out must be outside the --source tree")
    cwd = Path.cwd().resolve()
    if cwd.is_relative_to(destination):
        raise ValueError("refusing to clean the current directory or one of its parents")
    if destination == Path.home().resolve() or destination == Path(destination.anchor):
        raise ValueError("refusing to clean a filesystem root or the home directory")


def _prepare_destination(out: Path) -> None:
    if out.is_symlink():
        raise ValueError(f"refusing to replace symlink {out}")
    if out.exists():
        if not out.is_dir():
            raise ValueError(f"{out} exists and is not a directory")
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)


def _write_readme(out: Path, run_ids: Sequence[str]) -> None:
    runs = "\n".join(f"- `{run_id}`" for run_id in run_ids)
    if not runs:
        runs = "- (no run artifacts passed the size caps)"
    (out / README_NAME).write_text(README_TEMPLATE.format(runs=runs), encoding="utf-8")


def build_demo_runs(source: str | Path, out: str | Path) -> list[RunStats]:
    """Copy the allowlisted files for every selected run that exists.

    Raises ``NoSelectedRuns`` when no selected run directory is present.
    """
    source = Path(source)
    out = Path(out)
    if not source.is_dir():
        raise NoSelectedRuns(f"source directory not found: {source}")
    selected = [
        run_id
        for run_id in RUN_IDS
        if (source / run_id).is_dir() and not (source / run_id).is_symlink()
    ]
    if not selected:
        raise NoSelectedRuns(f"none of the selected runs exist under {source}")

    _guard_destination(source.resolve(), out.resolve())
    _prepare_destination(out)

    stats: list[RunStats] = []
    included: list[str] = []
    copied_bytes = 0
    for run_id in selected:
        run_dir = source / run_id
        files = 0
        total = 0
        for relative in _candidates(run_dir):
            path = run_dir / relative
            label = f"{run_id}/{relative.as_posix()}"
            try:
                size = path.lstat().st_size
            except OSError as error:
                print(f"skip {label}: {error}", file=sys.stderr)
                continue
            if size > MAX_FILE_BYTES:
                print(
                    f"skip {label}: {size} bytes exceeds the {MAX_FILE_BYTES}-byte "
                    "per-file cap",
                    file=sys.stderr,
                )
                continue
            if copied_bytes + size > MAX_TOTAL_BYTES:
                print(
                    f"skip {label}: total would exceed the {MAX_TOTAL_BYTES}-byte cap",
                    file=sys.stderr,
                )
                continue
            destination = out / run_id / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, destination)
            files += 1
            total += size
            copied_bytes += size
        stats.append(RunStats(run_id=run_id, files=files, bytes=total))
        if files:
            included.append(run_id)
        print(f"{run_id}: {files} files, {total} bytes")

    _write_readme(out, included)
    print(f"total: {sum(item.files for item in stats)} files, {copied_bytes} bytes")
    return stats


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Build the curated read-only demo-runs tree for the review API."
    )
    parser.add_argument(
        "--out",
        default="demo-runs",
        help="destination directory (default: %(default)s)",
    )
    parser.add_argument(
        "--source",
        default="runs",
        help="recorded runs root (default: %(default)s)",
    )
    args = parser.parse_args(argv)
    try:
        build_demo_runs(args.source, args.out)
    except NoSelectedRuns as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
